#!/usr/bin/env node
/**
 * generate-registry-rules.mjs — registries/<id>/rules/*.md →
 * src/registry/<id>/rules.generated.ts (one string, ships as the
 * registry's `prompt.extraRules`).
 *
 * THE hand-editable home for generation rules. Drop a .md file in the
 * rules/ dir (numeric prefixes control order: 00-house-rules.md,
 * 10-project-observations.md), re-run this, restart dev — the content
 * rides verbatim into every generation prompt for projects on this
 * registry. Files are concatenated in filename order, separated by
 * blank lines; a leading `# Title` line is kept (models read headings
 * fine). Keep rules terse — every char is prompt tokens on every turn.
 *
 *   node scripts/generate-registry-rules.mjs [registry-id=brightlocal]
 *
 * Per-PROJECT (not per-registry) instructions are a separate channel:
 * the project's `instructions` field, editable in Project Settings.
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const id = process.argv[2] ?? "brightlocal";
if (!/^[a-z][a-z0-9-]*$/.test(id)) {
  console.error("usage: generate-registry-rules.mjs <registry-id>");
  process.exit(1);
}
const RULES_DIR = join(__dirname, "..", "registries", id, "rules");
const OUT_FILE = join(__dirname, "..", "src", "registry", id, "rules.generated.ts");

if (!existsSync(RULES_DIR)) {
  console.error(`no rules dir: registries/${id}/rules`);
  process.exit(1);
}

const files = readdirSync(RULES_DIR).filter((f) => f.endsWith(".md")).sort();
const entries = files
  .map((f) => ({
    id: f.replace(/\.md$/, ""),
    name: f,
    content: readFileSync(join(RULES_DIR, f), "utf-8").trim(),
  }))
  .filter((e) => e.content);
const combined = entries.map((e) => e.content).join("\n\n");

const CONST = id.toUpperCase().replace(/-/g, "_");
mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(
  OUT_FILE,
  `// AUTO-GENERATED by scripts/generate-registry-rules.mjs from
// registries/${id}/rules/*.md — the .md files are the authoring home
// (hand-editable, concatenated in filename order); do not hand-edit.
import type { RegistryRuleFile } from "../types";

/** Per-file rules — lets the Rules screen list/toggle each file. */
export const ${CONST}_RULES_FILES: readonly RegistryRuleFile[] = ${JSON.stringify(entries, null, 2)};

/** All files concatenated — the pre-toggle fallback. */
export const ${CONST}_RULES = ${JSON.stringify(combined)};
`,
);
console.log(
  `[rules] ${files.length} file(s) (${combined.length} chars) → src/registry/${id}/rules.generated.ts`,
);
