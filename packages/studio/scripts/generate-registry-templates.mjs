#!/usr/bin/env node
/**
 * generate-registry-templates.mjs — registries/<id>/templates/*.jsx →
 * src/registry/<id>/templates.generated.ts.
 *
 * Templates are HAND-AUTHORED full-page scaffolds (the BYODS pilot's
 * "scaffolds"): complete modules with imports + export default, applied
 * directly as a new screen's appSource when picked from the Starters /
 * empty-state chips. First header line = "<Label> — <description>";
 * id = filename. Edit the .jsx, re-run this, done.
 *
 *   node scripts/generate-registry-templates.mjs [registry-id=brightlocal]
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const id = process.argv[2] ?? "brightlocal";
if (!/^[a-z][a-z0-9-]*$/.test(id)) {
  console.error("usage: generate-registry-templates.mjs <registry-id>");
  process.exit(1);
}
const TEMPLATES_DIR = join(__dirname, "..", "registries", id, "templates");
const OUT_FILE = join(__dirname, "..", "src", "registry", id, "templates.generated.ts");

if (!existsSync(TEMPLATES_DIR)) {
  console.error(`no templates dir: registries/${id}/templates`);
  process.exit(1);
}

const templates = [];
for (const f of readdirSync(TEMPLATES_DIR).filter((f) => f.endsWith(".jsx")).sort()) {
  const raw = readFileSync(join(TEMPLATES_DIR, f), "utf-8");
  const firstLine = (raw.split("\n")[0] ?? "").replace(/^\/\/\s*/, "");
  const [label, description] = firstLine.split("—").map((s) => s.trim());
  templates.push({
    id: f.replace(/\.jsx$/, ""),
    label: label || f.replace(/\.jsx$/, ""),
    description: description || "",
    // Source keeps the header comments — they carry provenance and the
    // "edit me here" pointer, useful in the screen's code view too.
    source: raw.trim(),
  });
}

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(
  OUT_FILE,
  `// AUTO-GENERATED by scripts/generate-registry-templates.mjs from
// registries/${id}/templates/*.jsx — the .jsx files are the authoring
// home (hand-editable full-page scaffolds); do not hand-edit this file.
import type { RegistryTemplate } from "../types";

export const ${id.toUpperCase().replace(/-/g, "_")}_TEMPLATES: readonly RegistryTemplate[] = ${JSON.stringify(templates, null, 2)} as const;
`,
);
console.log(
  `[templates] ${templates.length} template(s) → src/registry/${id}/templates.generated.ts`,
);
