#!/usr/bin/env node
/**
 * generate-registry-lib.mjs — registries/<id>/lib/*.jsx →
 * src/registry/<id>/lib.generated.ts.
 *
 * Lib modules are SHARED USER-LAND COMPONENT MODULES (STUDIO-FLOWS M0,
 * "@brightlocal/proposal"): hand-authored JSX with named exports,
 * compiled into the registry bundle as SOURCE STRINGS keyed by import
 * specifier ("@<registry-id>/<filename>"). Screens import from the
 * specifier instead of carrying in-file copies:
 *
 *   import { AppLayoutShell, ProposalSidebar } from "@brightlocal/proposal";
 *
 * Consumers:
 *   - external sandbox: sucrase-compiles each module at boot and
 *     registers it BEFORE screen modules load.
 *   - chat-sandpack: ships the same source as a file in the Sandpack
 *     file map with the import aliased to it (parity: an exported
 *     sandbox = screen + lib file, runs as-is).
 *
 * Edit the .jsx, re-run this, done. Harvest scripts never touch lib/.
 *
 *   node scripts/generate-registry-lib.mjs [registry-id=brightlocal]
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const id = process.argv[2] ?? "brightlocal";
if (!/^[a-z][a-z0-9-]*$/.test(id)) {
  console.error("usage: generate-registry-lib.mjs <registry-id>");
  process.exit(1);
}
const LIB_DIR = join(__dirname, "..", "registries", id, "lib");
const OUT_FILE = join(__dirname, "..", "src", "registry", id, "lib.generated.ts");

if (!existsSync(LIB_DIR)) {
  console.error(`no lib dir: registries/${id}/lib`);
  process.exit(1);
}

const modules = {};
for (const f of readdirSync(LIB_DIR).filter((f) => f.endsWith(".jsx")).sort()) {
  // Import specifier: "@<registry-id>/<filename>" — for brightlocal the
  // registry id and the npm scope coincide, which is what makes the
  // specifier read like a real package ("@brightlocal/proposal").
  const spec = `@${id}/${f.replace(/\.jsx$/, "")}`;
  modules[spec] = readFileSync(join(LIB_DIR, f), "utf-8").trim();
}

// ─── Named datasets: lib/data/*.json → the "@<id>/data" module ────────
// Raw, hand-editable JSON — each file is a PARTIAL patch deep-merged
// over the lib's default data by the consumer (ProposalDataProvider).
// Filename = dataset name. JSON on purpose: it can't carry JSX, which
// keeps datasets pure content. Folded into a tiny generated module so
// lib code can `import { DATASETS } from "@<id>/data"` through the
// same lib-module seam (lib-to-lib requires are supported).
const DATA_DIR = join(LIB_DIR, "data");
if (existsSync(DATA_DIR)) {
  const datasets = {};
  for (const f of readdirSync(DATA_DIR).filter((f) => f.endsWith(".json")).sort()) {
    const raw = readFileSync(join(DATA_DIR, f), "utf-8");
    try {
      datasets[f.replace(/\.json$/, "")] = JSON.parse(raw);
    } catch (e) {
      console.error(`[lib] invalid JSON in lib/data/${f}: ${e.message}`);
      process.exit(1);
    }
  }
  if (Object.keys(datasets).length > 0) {
    modules[`@${id}/data`] =
      `// AUTO-GENERATED from registries/${id}/lib/data/*.json — edit the JSON.\n` +
      `export const DATASETS = ${JSON.stringify(datasets, null, 2)};\n` +
      `export default DATASETS;\n`;
  }
}

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(
  OUT_FILE,
  `// AUTO-GENERATED by scripts/generate-registry-lib.mjs from
// registries/${id}/lib/*.jsx — the .jsx files are the authoring home
// (shared user-land component modules); do not hand-edit this file.

export const ${id.toUpperCase().replace(/-/g, "_")}_LIB_MODULES: Readonly<Record<string, string>> = ${JSON.stringify(modules, null, 2)} as const;
`,
);
console.log(
  `[lib] ${Object.keys(modules).length} module(s) → src/registry/${id}/lib.generated.ts`,
);
