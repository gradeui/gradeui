// a grid where some cards quantify and others do not reads as an oversight.
const TREND_STYLE = "arrow"; // "value" | "arrow"

// A DELTA IS ONLY READABLE IN ITS OWN UNIT (Ali, 7 Sep: "Up 67% for a review
// average doesnt help me"). Quite right, and it was wrong twice: the Tracker
// card's headline is an average RATING, but the trend under it was plotting
// review VOLUME, and then expressing it as a percentage. "Up 67%" of a 4.7
// average is not a quantity that exists. So the unit travels with the number:
//
//   rating   +0.12 / -0.12   points of a five point scale, two decimals
//   percent  +8%             a proportion, where the base is obvious
//   count    +3              whole things, where the base is small
//
// DIRECTION IS NOT SENTIMENT. Up is good for a rating and bad for a queue of
// unanswered reviews, so the arrow says which way it moved and `goodWhen`
// decides whether that is green or red. Colour is not the only carrier: the
// arrow and the figure both still read with colour removed.
function formatDelta(value, format) {
  const n = Math.abs(value);
  if (format === "rating") return n.toFixed(2);
  if (format === "percent") return `${Math.round(n)}%`;
  return String(Math.round(n));
}

function TrendChip({ trend, hook }) {
  if (!trend) return null;
  const up = trend.value >= 0;
  const good = (trend.goodWhen ?? "up") === (up ? "up" : "down");
  return (
    <span
      className="text-muted-foreground flex items-baseline gap-1 text-xs"
      data-hook={`${hook}-trend`}
    >
      <span className={good ? "text-success font-medium" : "text-destructive font-medium"}>
        {up ? "\u2191" : "\u2193"}
        {TREND_STYLE === "value" ? ` ${formatDelta(trend.value, trend.format)}` : ""}
      </span>
      <span>{trend.period}</span>
    </span>
  );
}

