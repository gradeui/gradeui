// PLAIN SVG, NOT RECHARTS. A sparkline is a polyline and a dot; pulling a
// charting library in for 60x20 pixels costs a dependency the hub does not
// otherwise have, and the panel renderer blocks network so every new import
// is a risk. This has no axes, no grid, no tooltip and no legend on purpose:
// at this size the only readable message is the SHAPE, and anything else is
// ink competing with the headline number beside it.
function Sparkline({ series = [], w = 72, h = 24, dataHook }) {
  if (series.length < 2) return null;
  const min = Math.min(...series);
  const max = Math.max(...series);
  const span = max - min || 1;
  // 1px inset top and bottom so the stroke is never clipped at the extremes.
  const pt = (v, i) => [
    (i / (series.length - 1)) * w,
    h - 1 - ((v - min) / span) * (h - 2),
  ];
  const pts = series.map(pt);
  const d = pts.map((q, i) => `${i ? "L" : "M"}${q[0].toFixed(1)},${q[1].toFixed(1)}`).join(" ");
  const last = pts[pts.length - 1];
  return (
    <svg
      width={w}
      height={h}
      viewBox={`0 0 ${w} ${h}`}
      className="overflow-visible"
      data-hook={dataHook}
      aria-hidden="true"
    >
      <path
        d={`${d} L${w},${h} L0,${h} Z`}
        fill="var(--ds-tailwind-colors-green-100)"
        opacity="0.5"
      />
      <path
        d={d}
        fill="none"
        stroke="var(--ds-tailwind-colors-green-600)"
        strokeWidth="1.5"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
      <circle cx={last[0]} cy={last[1]} r="2" fill="var(--ds-tailwind-colors-green-600)" />
    </svg>
  );
}

